"""Build results/summary.md from the saved runs. Every number in the article comes from here."""
import json
import re
import statistics as st
from pathlib import Path

R = Path(__file__).parent / "results"
h = json.load(open(R / "uaef-vs-agentcore-haiku-4-5.json"))
o = json.load(open(R / "uaef-vs-agentcore-opus-4-6.json"))
M = ["accuracy", "completeness", "answer_relevance", "hallucination_score", "hallucination_score@world"]


def mean(row, m):
    v = [r[m]["score"] for r in row["uaef_runs"] if r.get(m) and r[m]["score"] is not None]
    return st.mean(v)


def ac(row, ev):
    v = row["agentcore"].get(ev)
    return v[0]["value"] if v else None


lines = ["# Summary (generated by summarize.py)", "",
         f"Judges: {h['judge']} x{h['runs']} runs, {o['judge']} x{o['runs']} run. Caching env: {h['caching']}.", "",
         "| q | AgentCore Correctness | AgentCore Faithfulness | UAEF accuracy H/O | completeness H/O | halluc (trace) H/O | halluc (world) H/O | relevance H/O |",
         "|---|---|---|---|---|---|---|---|"]
for rh, ro in zip(h["rows"], o["rows"]):
    def pair(m):
        return f"{mean(rh, m):.2f} / {mean(ro, m):.2f}"
    lines.append(f"| q{rh['id']} | {ac(rh,'Builtin.Correctness')} | {ac(rh,'Builtin.Faithfulness')} | {pair('accuracy')} | {pair('completeness')} | {pair('hallucination_score')} | {pair('hallucination_score@world')} | {pair('answer_relevance')} |")

# run-to-run spread for the judge that ran 3 times
spread = [max(v) - min(v) for r in h["rows"] for m in M
          for v in [[x[m]["score"] for x in r["uaef_runs"]]]]
lines += ["", f"Haiku run-to-run: max spread across 3 runs over {len(spread)} (question, metric) cells = {max(spread):.2f}; cells with any spread = {sum(s > 0 for s in spread)}."]

# judge disagreement
diffs = {m: [abs(mean(a, m) - mean(b, m)) for a, b in zip(h["rows"], o["rows"])] for m in M}
for m in M:
    big = sum(d >= 0.25 for d in diffs[m])
    lines.append(f"Haiku vs Opus on {m}: mean abs diff {st.mean(diffs[m]):.2f}, questions differing by >=0.25: {big}/10.")

# the false answer
q5h, q5o = h["rows"][4], o["rows"][4]
lines += ["", f"q5 (false answer, AgentCore Correctness={ac(q5h,'Builtin.Correctness')}): accuracy H={mean(q5h,'accuracy'):.2f} O={mean(q5o,'accuracy'):.2f}; "
          f"completeness H={mean(q5h,'completeness'):.2f} O={mean(q5o,'completeness'):.2f}; halluc world H={mean(q5h,'hallucination_score@world'):.2f} O={mean(q5o,'hallucination_score@world'):.2f}."]

# which questions each method flags (<0.5 on accuracy)
flag = lambda rows: [f"q{r['id']}" for r in rows if mean(r, "accuracy") < 0.5]
lines.append(f"Flagged by UAEF accuracy<0.5: Haiku {flag(h['rows'])}, Opus {flag(o['rows'])}. AgentCore Correctness<1: "
             f"{[f'q{r['id']}' for r in h['rows'] if ac(r,'Builtin.Correctness') != 1]}.")

# wall-clock from the run log (optional: the log is not shipped with the repo)
log = R / "run-all.log"
if log.exists():
    ts = re.findall(r"^(\d{4}-\d\d-\d\dT[\d:.]+)", log.read_text(), re.M)
    lines.append(f"Log span: {ts[0]} to {ts[-1]} (UTC, both judges).")
(R / "summary.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
